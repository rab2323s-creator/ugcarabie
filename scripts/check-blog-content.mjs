import fs from 'node:fs/promises'
import path from 'node:path'
import assert from 'node:assert/strict'
import {blogArticles,blogCategories,blogInfo,blogPath} from '../src/lib/blogContent.js'
const root=path.resolve('dist')
const escape=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]))
const read=async file=>fs.readFile(path.resolve(file),'utf8')
const count=blogArticles.length
assert.equal(count,7,'Seven standalone HTML articles')
assert.equal(blogCategories.length,3,'Three editorial categories')
assert.equal(new Set(blogArticles.map(a=>a.slug)).size,count,'Unique Arabic slugs')
for(const category of blogCategories)assert.equal(blogArticles.filter(a=>a.category===category.id).length,category.id==='creators'?3:2,'Expected guides in '+category.id)
const listing=await read('dist/blog/index.html')
const sourceListing=await read('blog/index.html')
assert.equal(listing,sourceListing,'Main blog index must be published directly from source HTML')
assert.ok(listing.includes('CollectionPage')&&listing.includes('ItemList'),'Blog index JSON-LD missing')
assert.ok(listing.includes('rel="canonical"')&&listing.includes('https://ugcarabie.com/blog/'),'Index canonical missing')
assert.ok(!listing.includes('id="root"')&&!listing.includes('/assets/index-'),'Blog index must be standalone, not React SPA')
await fs.access('dist/blog/site.css')
await fs.access('dist/blog/static.css')
await fs.access('dist/blog/site.js')
for(const article of blogArticles){
 assert.match(article.slug,/^[\p{Script=Arabic}0-9A-Za-z-]+$/u,'Arabic URL')
 assert.ok(article.slug.includes('UGC'),'Keep UGC in English')
 assert.ok(article.metaDescription.length>75&&article.metaDescription.length<165,'SEO description')
 assert.ok(article.seoTitle.length>=25&&article.seoTitle.length<82,'SEO title')
 assert.ok(article.image.startsWith('/images/blog/')&&article.image.endsWith('.webp'),'WebP media path')
 const source=await read('blog/'+article.slug+'/index.html')
 const html=await read('dist/blog/'+article.slug+'/index.html')
 assert.ok(source.includes('<!-- BLOG_IMAGE_META -->'),'Image metadata token should exist in editable HTML')
 assert.ok(!html.includes('<!-- BLOG_IMAGE_META -->'),'Publish step did not finish')
 assert.ok(!html.includes('id="root"'),'React should not own article route')
 assert.ok(html.includes('<h1>'+escape(article.title)+'</h1>'),'Article title must match manifest')
 assert.ok(html.includes('<title>'+escape(article.seoTitle)+' | UGC Arabie</title>'),'Meta title must match manifest')
 assert.ok(html.includes('content="'+escape(article.metaDescription)+'"'),'Meta description must match manifest')
 const canonical='rel="canonical" href="https://ugcarabie.com'+blogPath(article)+'/"'
 assert.ok(html.includes(canonical),'Canonical missing '+article.slug)
 assert.ok(html.includes('name="robots" content="index'),'Article must be indexable')
 const answerSections=[...html.matchAll(/<section class="blog-article-section" id="([^"]+)"><h2>([^<]+)<\/h2><p class="blog-direct-answer">([^<]+)<\/p>/g)]
 assert.ok(answerSections.length>=5,'Five or more direct-answer H2 sections '+article.slug)
 assert.ok(answerSections.every(([,id,heading,answer])=>heading.endsWith('؟')&&answer.length>100),'Incomplete H2 answers '+article.slug)
 const textOnly=html.replace(/<script[\s\S]*?<\/script>/g,'').replace(/<style[\s\S]*?<\/style>/g,'').replace(/<[^>]*>/g,' ')
 const words=textOnly.trim().split(/\s+/u)
 assert.ok(words.length>570,'Article is too short '+article.slug)
 const match=html.match(/<script id="blog-schema" type="application\/ld\+json">([\s\S]*?)<\/script>/)
 assert.ok(match,'Article structured data missing')
 const schema=JSON.parse(match[1])['@graph']
 assert.ok(schema.some(x=>x['@type']==='BlogPosting'),'BlogPosting schema missing')
 assert.ok(schema.some(x=>x['@type']==='BreadcrumbList'),'Breadcrumb schema missing')
 assert.equal(schema.find(x=>x['@type']==='BlogPosting').headline,article.title,'Schema headline mismatched')
 assert.equal(schema.find(x=>x['@type']==='BlogPosting').datePublished,article.published,'Published date changed')
 const ready=await fs.access(path.join(root,article.image.slice(1))).then(()=>true,()=>false)
 const post=schema.find(x=>x['@type']==='BlogPosting')
 if(ready){
  const obj=schema.find(x=>x['@type']==='ImageObject'&&x['@id']===post.image?.['@id'])
  assert.equal(obj?.contentUrl,'https://ugcarabie.com'+article.image,'ImageObject points to cover')
  assert.equal(obj?.description,article.imageAlt,'ImageObject description matches alt')
  assert.ok(html.includes('src="'+escape(article.image)+'"'),'Cover source missing')
  assert.ok(html.includes('alt="'+escape(article.imageAlt)+'"'),'Cover alt missing')
  assert.ok(html.includes('property="og:image" content="https://ugcarabie.com'+article.image+'"'),'OG cover mismatch')
 }
 assert.equal(Boolean(post.image),ready,'Image schema must match actual file')
 assert.ok(html.includes('href="/blog/"')&&html.includes('id="article-related"'),'Internal links missing')
 console.log('PASS',article.slug,answerSections.length+' search-answer sections',words.length+' words',ready?'WebP ready':'image pending')
}
const sitemap=await read('dist/sitemap.xml')
assert.ok(sitemap.includes('https://ugcarabie.com/blog/'),'Blog home missing from sitemap')
for(const article of blogArticles)assert.ok(sitemap.includes('https://ugcarabie.com'+blogPath(article)+'/'),'Sitemap missing '+article.slug)
const shoot=blogArticles.find(a=>a.slug==='كيف-تصور-فيديو-UGC-احترافي-بالجوال-من-المنزل')
assert.ok(shoot,'Shooting guide missing')
assert.equal(shoot.image,'/images/blog/how-to-film-ugc-video-at-home.webp','Shooting guide cover must use uploaded image')
const shootFile=await fs.readFile(path.join(root,shoot.image.slice(1)))
assert.equal(shootFile.toString('ascii',0,4),'RIFF','Shooting cover RIFF header')
assert.equal(shootFile.toString('ascii',8,12),'WEBP','Shooting cover WebP header')
assert.ok(sitemap.includes('<image:loc>https://ugcarabie.com'+shoot.image+'</image:loc>'),'Shooting cover missing from image sitemap')
assert.ok(listing.includes('src="'+shoot.image+'"'),'Shooting guide card cover missing')
const shootHtml=await read('blog/'+shoot.slug+'/index.html')
assert.ok(shootHtml.includes('<figcaption>'+shoot.imageCaption),'Shooting guide caption missing')
for(const article of blogArticles.filter(a=>a.slug!==shoot.slug)){
 const source=await read('blog/'+article.slug+'/index.html')
 assert.ok(source.includes('href="/blog/'+shoot.slug+'/"'),'Incoming article link missing '+article.slug)
 assert.ok(shootHtml.includes('href="/blog/'+article.slug+'/"'),'Outgoing article link missing '+article.slug)
}
console.log('PASS: seven complete standalone Arabic HTML pages, category index, schema, sitemap')
